package fi.ak.smartvoice.audio

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.nio.ByteBuffer
import java.nio.ByteOrder

class WavReaderTest {

    @Test
    fun `read parses valid mono 16kHz WAV generated by WavWriter`() {
        val sampleRate = 16000
        val numSamples = 16000 // 1.0 second
        val pcm = ByteArray(numSamples * 2)
        val buf = ByteBuffer.wrap(pcm).order(ByteOrder.LITTLE_ENDIAN)

        // Write a 440 Hz test sine wave or known values
        val expected = FloatArray(numSamples)
        for (i in 0 until numSamples) {
            val v = (i % 1000 - 500).toShort()
            buf.putShort(i * 2, v)
            expected[i] = v / 32768.0f
        }

        val wavBytes = WavWriter.build(pcm, sampleRate = sampleRate, channels = 1)
        val result = WavReader.read(wavBytes)

        assertEquals(sampleRate, result.sampleRate)
        assertEquals(1, result.channels)
        assertEquals(1.0f, result.durationSeconds, 0.01f)
        assertEquals(numSamples, result.samples.size)

        for (i in 0 until 100) {
            assertEquals(expected[i], result.samples[i], 0.0001f)
        }
    }

    @Test
    fun `read parses stereo audio and downmixes to mono`() {
        val sampleRate = 16000
        val numFrames = 500
        val channels = 2
        val pcm = ByteArray(numFrames * channels * 2)
        val buf = ByteBuffer.wrap(pcm).order(ByteOrder.LITTLE_ENDIAN)

        for (i in 0 until numFrames) {
            buf.putShort((i * 2) * 2, 1000.toShort())     // Left
            buf.putShort((i * 2 + 1) * 2, 3000.toShort()) // Right
        }

        val wavBytes = WavWriter.build(pcm, sampleRate = sampleRate, channels = 2)
        val result = WavReader.read(wavBytes)

        assertEquals(sampleRate, result.sampleRate)
        assertEquals(2, result.channels)
        assertEquals(numFrames, result.samples.size)

        // Average of 1000 and 3000 is 2000
        val expectedVal = 2000 / 32768.0f
        assertEquals(expectedVal, result.samples[0], 0.0001f)
    }
}
